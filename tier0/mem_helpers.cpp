// Both 32-bit halves equal 0xffeeffee, so every naturally aligned DWORD (and the
// byte sequence of the tail) is identical on little- and big-endian targets and
// matches the original 32-bit/64-bit implementations byte for byte.
constexpr std::uint64_t kFeeFee64{ 0xffeeffeeffeeffeeULL };

void InitializeToFeeFee( void *pMem, size_t nSize ) noexcept
{
	auto *pOut = static_cast<unsigned char *>( pMem );

	// memcpy of a constant compiles to plain stores (vectorized at -O2) and makes no
	// alignment or strict-aliasing assumptions, unlike the old uint64_t*/uint32_t* casts.
	// Unrolled to 32 bytes per iteration for large blocks.
	while ( nSize >= 4 * sizeof( kFeeFee64 ) )
	{
		std::memcpy( pOut + 0,  &kFeeFee64, sizeof( kFeeFee64 ) );
		std::memcpy( pOut + 8,  &kFeeFee64, sizeof( kFeeFee64 ) );
		std::memcpy( pOut + 16, &kFeeFee64, sizeof( kFeeFee64 ) );
		std::memcpy( pOut + 24, &kFeeFee64, sizeof( kFeeFee64 ) );
		pOut  += 4 * sizeof( kFeeFee64 );
		nSize -= 4 * sizeof( kFeeFee64 );
	}
	while ( nSize >= sizeof( kFeeFee64 ) )
	{
		std::memcpy( pOut, &kFeeFee64, sizeof( kFeeFee64 ) );
		pOut  += sizeof( kFeeFee64 );
		nSize -= sizeof( kFeeFee64 );
	}
	// 0..7 tail bytes continue the pattern from its first byte. Fixed-size copies
	// only, so no out-of-line memcpy call for small blocks.
	if ( nSize >= sizeof( std::uint32_t ) )
	{
		std::memcpy( pOut, &kFeeFee64, sizeof( std::uint32_t ) );
		pOut  += sizeof( std::uint32_t );
		nSize -= sizeof( std::uint32_t );
	}
	const auto *pPattern = reinterpret_cast<const unsigned char *>( &kFeeFee64 );
	for ( size_t i = 0; i < nSize; ++i )
		pOut[i] = pPattern[i];
}

