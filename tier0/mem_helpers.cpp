// dimhotepus: Position in g_RandomValues. Wraps modulo 2^N, a multiple of 256,
// so masking with 0xFF stays continuous across the wrap on 32- and 64-bit.
std::atomic<size_t> g_iCurRandomValueOffset{ 0 };

void InitializeToRandom( void *pMem, size_t nSize ) noexcept
{
	auto *pOut = static_cast<unsigned char *>( pMem );

	// dimhotepus: Reserve the whole range with ONE atomic RMW per allocation instead of
	// one per byte (which serialized all allocating threads on a single cache line).
	// Single-threaded output is byte-identical to the old per-byte loop, and each
	// block now gets a contiguous run of the pattern even under contention.
	size_t iOffset{ g_iCurRandomValueOffset.fetch_add( nSize, std::memory_order_relaxed ) & 0xFF };

	while ( nSize )
	{
		const size_t nChunk{ (std::min)( nSize, sizeof( g_RandomValues ) - iOffset ) };
		std::memcpy( pOut, g_RandomValues + iOffset, nChunk );
		pOut   += nChunk;
		nSize  -= nChunk;
		iOffset = 0;
	}
}

